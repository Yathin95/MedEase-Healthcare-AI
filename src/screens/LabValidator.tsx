//  Module 4 — Lab Report Validator & Quack Detector
// ─────────────────────────────────────────────
import { useState } from 'react';
import {
  FlaskConical,
  Pill,
  Loader2,
  AlertTriangle,
  CheckCircle2,
  FileText,
  Download,
  ShieldAlert,
  Sparkles,
  ClipboardList,
} from 'lucide-react';
import type { DoctorClarificationCard, Toast } from '../types';
import { validateLabReport } from '../geminiService';
import { saveClarificationCard } from '../ledgerService';

interface LabValidatorProps {
  onAddToast: (t: Omit<Toast, 'id'>) => void;
  onCardCreated: () => void;
}

export default function LabValidator({ onAddToast, onCardCreated }: LabValidatorProps) {
  const [labText, setLabText] = useState('');
  const [drugName, setDrugName] = useState('');
  const [analysing, setAnalysing] = useState(false);
  const [card, setCard] = useState<DoctorClarificationCard | null>(null);

  const handleAnalyse = async () => {
    if (!labText.trim() || !drugName.trim()) {
      onAddToast({ type: 'warning', message: 'Please fill in both the lab report markers and the prescribed drug.' });
      return;
    }
    setAnalysing(true);
    setCard(null);
    try {
      const result = await validateLabReport(labText.trim(), drugName.trim());
      const newCard: DoctorClarificationCard = {
        id: crypto.randomUUID(),
        createdAt: new Date().toISOString(),
        labMarkers: labText.trim(),
        prescribedDrug: drugName.trim(),
        aiAnalysis: result.analysis,
        questions: result.questions,
        acknowledged: false,
      };
      setCard(newCard);

      if (result.hasConflict) {
        saveClarificationCard(newCard);
        onCardCreated();
        onAddToast({
          type: 'warning',
          message: '⚠️ Potential concern detected. A Doctor Clarification Card has been saved and shared with caregivers.',
          duration: 8000,
        });
      } else {
        onAddToast({ type: 'success', message: '✅ No significant concerns detected. Always confirm with your doctor.' });
      }
    } catch {
      onAddToast({ type: 'error', message: 'Analysis failed. Please check your API key.' });
    } finally {
      setAnalysing(false);
    }
  };

  const exportCard = () => {
    if (!card) return;
    const content = [
      '═══════════════════════════════════════',
      '       MEDEASE DOCTOR CLARIFICATION CARD',
      '═══════════════════════════════════════',
      '',
      `Date: ${new Date(card.createdAt).toLocaleString()}`,
      '',
      '── Lab Report Markers Entered ──────────',
      card.labMarkers,
      '',
      `── Prescribed Drug ─────────────────────`,
      card.prescribedDrug,
      '',
      '── AI Analysis (Not Medical Advice) ────',
      card.aiAnalysis,
      '',
      '── Questions to Ask Your Doctor ────────',
      ...card.questions.map((q, i) => `${i + 1}. ${q}`),
      '',
      '── Safety Reminder ─────────────────────',
      'Only a licensed physician can interpret your lab results and adjust your treatment plan.',
      'This card is generated by AI and is NOT a medical diagnosis.',
      '',
      '═══════════════════════════════════════',
    ].join('\n');

    const blob = new Blob([content], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `medease_clarification_${new Date().toISOString().split('T')[0]}.txt`;
    a.click();
    URL.revokeObjectURL(url);
    onAddToast({ type: 'success', message: 'Doctor Clarification Card exported.' });
  };

  return (
    <div className="space-y-5 animate-fade-in">
      {/* Title */}
      <div className="text-center space-y-1.5">
        <div className="w-14 h-14 rounded-2xl bg-gradient-to-br from-blue-600 to-cyan-600 flex items-center justify-center mx-auto shadow-lg shadow-blue-900/30">
          <FlaskConical className="w-7 h-7 text-white" />
        </div>
        <h2 className="text-2xl font-bold text-white">Lab Report Validator</h2>
        <p className="text-slate-400 text-sm">Check if your prescription aligns with your lab results</p>
      </div>

      {/* Clinical boundary notice */}
      <div className="flex items-start gap-3 px-4 py-3 rounded-xl bg-red-950/30 border border-red-800/30">
        <ShieldAlert className="w-5 h-5 text-red-400 flex-shrink-0 mt-0.5" />
        <p className="text-xs text-slate-400">
          <strong className="text-red-300">Clinical Boundary:</strong> This AI will never instruct you to stop or adjust medication, nor make a diagnosis. It only generates questions for your licensed physician.
        </p>
      </div>

      {/* Input form */}
      <div className="glass-card p-5 space-y-4">
        <div className="space-y-2">
          <label className="flex items-center gap-2 text-sm font-semibold text-slate-300">
            <FlaskConical className="w-4 h-4 text-blue-400" />
            Lab Report Markers / Values
          </label>
          <textarea
            value={labText}
            onChange={e => setLabText(e.target.value)}
            placeholder="e.g. HbA1c: 8.2%, eGFR: 45 mL/min, Potassium: 5.8 mEq/L, Creatinine: 1.9 mg/dL"
            rows={4}
            className="input-field resize-none"
          />
          <p className="text-xs text-slate-600">Paste your lab values here exactly as they appear on the report.</p>
        </div>

        <div className="space-y-2">
          <label className="flex items-center gap-2 text-sm font-semibold text-slate-300">
            <Pill className="w-4 h-4 text-violet-400" />
            Newly Prescribed Drug
          </label>
          <input
            type="text"
            value={drugName}
            onChange={e => setDrugName(e.target.value)}
            placeholder="e.g. Metformin 500mg, Lisinopril 10mg"
            className="input-field"
          />
        </div>

        <button
          onClick={handleAnalyse}
          disabled={analysing}
          className="btn-primary w-full flex items-center justify-center gap-2 disabled:opacity-50 disabled:cursor-not-allowed"
        >
          {analysing ? (
            <><Loader2 className="w-5 h-5 animate-spin" /> Analysing with AI…</>
          ) : (
            <><Sparkles className="w-5 h-5" /> Analyse with Gemini</>
          )}
        </button>
      </div>

      {/* Result card */}
      {card && (
        <div className="space-y-4 animate-slide-in-up">
          {/* Status badge */}
          <div className={`glass-card p-4 flex items-center gap-3 ${card.acknowledged ? 'border-emerald-500/30' : 'border-amber-500/30'}`}>
            {card.acknowledged ? (
              <CheckCircle2 className="w-8 h-8 text-emerald-400 flex-shrink-0" />
            ) : (
              <AlertTriangle className="w-8 h-8 text-amber-400 flex-shrink-0" />
            )}
            <div>
              <p className="font-bold text-white">
                {card.acknowledged ? 'No Critical Conflict' : 'Potential Concern Detected'}
              </p>
              <p className="text-xs text-slate-400 mt-0.5">
                {card.acknowledged
                  ? 'AI found no critical misalignment. Confirm with your doctor.'
                  : 'A Doctor Clarification Card has been generated and saved.'}
              </p>
            </div>
          </div>

          {/* AI Analysis */}
          <div className="glass-card p-5 space-y-3">
            <div className="flex items-center gap-2 mb-1">
              <Sparkles className="w-4 h-4 text-violet-400" />
              <h3 className="font-semibold text-white">AI Analysis</h3>
              <span className="badge-pill bg-violet-500/20 text-violet-300 ml-auto text-[10px]">Not Medical Advice</span>
            </div>
            <p className="text-sm text-slate-300 leading-relaxed">{card.aiAnalysis}</p>
          </div>

          {/* Questions for doctor */}
          <div className="glass-card p-5 space-y-3">
            <div className="flex items-center gap-2">
              <ClipboardList className="w-4 h-4 text-emerald-400" />
              <h3 className="font-semibold text-white">Questions to Ask Your Doctor</h3>
            </div>
            <div className="space-y-2">
              {card.questions.map((q, i) => (
                <div key={i} className="flex items-start gap-3 bg-slate-800/40 rounded-xl p-3">
                  <span className="w-6 h-6 rounded-full bg-emerald-500/20 text-emerald-400 text-xs font-bold flex items-center justify-center flex-shrink-0 mt-0.5">
                    {i + 1}
                  </span>
                  <p className="text-sm text-slate-300">{q}</p>
                </div>
              ))}
            </div>
          </div>

          {/* Safety note */}
          <div className="flex items-start gap-3 px-4 py-3 rounded-xl bg-slate-800/40 border border-slate-700/30">
            <FileText className="w-4 h-4 text-slate-500 flex-shrink-0 mt-0.5" />
            <p className="text-xs text-slate-500 italic">
              Only a licensed physician can interpret your lab results and adjust your treatment plan. This AI analysis is for informational purposes only.
            </p>
          </div>

          {/* Export button */}
          <button onClick={exportCard} className="btn-ghost w-full flex items-center justify-center gap-2">
            <Download className="w-4 h-4" /> Export Doctor Clarification Card
          </button>
        </div>
      )}
    </div>
  );
}
